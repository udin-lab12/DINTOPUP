-- Skrip ini membuat tabel (users, products, orders) sekaligus mengisi 20 data produk asli DINTOPUP.

CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id UUID UNIQUE,
  name TEXT NOT NULL,
  full_name TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL DEFAULT '',
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
  whatsapp TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  game TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('topup', 'joki')),
  rank_tier TEXT NOT NULL DEFAULT '',
  price INTEGER NOT NULL CHECK (price > 0),
  unit_label TEXT NOT NULL,
  description TEXT NOT NULL,
  image_url TEXT NOT NULL,
  is_popular BOOLEAN NOT NULL DEFAULT FALSE,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code TEXT NOT NULL UNIQUE,
  user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  product_id BIGINT NOT NULL,
  product_name TEXT NOT NULL,
  game TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('topup', 'joki')),
  quantity INTEGER NOT NULL DEFAULT 1,
  total_price BIGINT NOT NULL,
  target_account_id TEXT NOT NULL,
  target_server TEXT NOT NULL DEFAULT '',
  joki_current_rank TEXT NOT NULL DEFAULT '',
  joki_target_rank TEXT NOT NULL DEFAULT '',
  joki_notes TEXT NOT NULL DEFAULT '',
  payment_method TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'processing', 'completed', 'cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_orders_user_id ON public.orders(user_id);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_category_game ON public.products(category, game);

